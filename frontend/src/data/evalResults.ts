export interface CaseResult {
  fixtureIndex: number
  query: string
  split: 'train' | 'test'
  mode: string
  effectiveMode: string
  injectedNames: string[]
  appliedTheme: string | null
  latencyMs: number
  retrievalPass: boolean
  injectionPass: boolean
  actionPass: boolean
  pass: boolean
  error: string | null
}

export interface ModeAggregate {
  mode: string
  n: number
  retrievalHitRate: number
  retrievalMRR: number
  injectionCoverRate: number
  actionPassRate: number
  passRate: number
  meanLatencyMs: number
}

export interface ModeResult extends ModeAggregate {
  splits: {
    test: ModeAggregate
    train: ModeAggregate
  }
}

export interface TraceAggregate {
  count: number
  sources: string[]
  mode: string
  topK: number
  retrievalCoverRate: number
  actionValidRate: number
  passRate: number
}

export interface EvalResults {
  generatedAt: string
  config: {
    modes: string[]
    topK: number
    maxInjectChars: number
    device: 'cpu'
    gateSplit: 'test'
  }
  fixtures: { total: number; train: number; test: number }
  modes: ModeResult[]
  cases: CaseResult[]
  traces: TraceAggregate | null
}

export function formatLatency(ms: number): string {
  if (ms < 0.5) return '< 1ms'
  if (ms < 10) return `${ms.toFixed(1)}ms`
  if (ms < 1000) return `${Math.round(ms)}ms`
  return `${(ms / 1000).toFixed(2)}s`
}

