export interface StageTiming {
  retrievalMs: number
  generationMs: number
  totalMs: number
  tokensGenerated: number
}

export interface AnswerScore {
  factRecall: number
  factsMissedDueToRetrievalMiss: string[]
  bannedViolation: boolean
  faithfulness: number
  unsupportedSentences: string[]
  pass: boolean
  appliedActionMatched: boolean
}

export interface ToolScoreRow {
  name: string
  score: number
  rank: number
  selected: boolean
}

export interface CaseResult {
  fixtureIndex: number
  query: string
  split: 'train' | 'test'
  mode: string
  effectiveMode: string
  selectedNames: string[]
  injectedNames: string[]
  rows: ToolScoreRow[]
  appliedTheme: string | null
  finalAnswer: string
  timings: StageTiming
  score: AnswerScore
  retrievalPass: boolean
  injectionPass: boolean
  actionPass: boolean
  answerPass: boolean
  chainPass: boolean
  error: string | null
}

export interface ModeAggregate {
  mode: string
  n: number
  retrievalHitRate: number
  retrievalMRR: number
  injectionCoverRate: number
  actionPassRate: number
  factRecall: number
  faithfulness: number
  hallucinationRate: number
  meanTotalLatencyMs: number
  answerPassRate: number
  chainPassRate: number
}

export interface ModeResult extends ModeAggregate {
  splits: {
    test: ModeAggregate
    train: ModeAggregate
  }
}

export interface TraceAggregate {
  count: number
  sources: string[]
  mode: string
  topK: number
  retrievalCoverRate: number
  actionValidRate: number
  groundedRate: number
  bannedViolationRate: number
  passRate: number
}

